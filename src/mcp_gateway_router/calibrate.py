"""Calibration against ToolRet's published leaderboard.

Our six-baseline ladder is ours, run on ToolRet with our own metrics. That is defensible
— their task is *rank tools for a query*, ours is *choose a subset under a token budget* —
but it leaves us with no external reference point. A poor ``semantic-retrieval`` score
would then be uninterpretable: we could not tell a real finding from a weak
implementation of our own retrieval.

So: run a published retriever over the same data, score it with the *standard* retrieval
metrics (nDCG@10, recall@k), and check we reproduce that model's reported number. This
sanity-checks the whole pipeline — loader, catalog identity, gold-label extraction,
embedding wiring — not just baseline 4. A silent bug anywhere upstream shows up here as a
number that is obviously wrong, rather than as a gate decision that is quietly wrong.

**Match the setting, or the check inverts.** The leaderboard publishes with- and
without-instruction tabs; the frontier scores query-only. Comparing a query-only run to
with-instruction numbers reports a correct run as broken, which is exactly what happened
before 2026-08-07. ``--no-instruction`` selects the band as well as the query text.

    uv run --extra bench python -m mcp_gateway_router.calibrate --model e5-base
    uv run --extra bench python -m mcp_gateway_router.calibrate --model bm25 --no-instruction
"""

