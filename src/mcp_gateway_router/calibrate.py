# A min/max band over 20 models spans 12.7–41.3, which would call almost anything "within
# band" — a check that cannot fail is not a check. So when we run a model that is itself on
# the leaderboard, compare like for like against *that model's* number. The band is only the
# fallback for the ToolRet-fine-tuned checkpoints, which have no published row.
#
# ±5 nDCG points is deliberately loose: our corpus is `web` (37k) rather than their full API
# corpus, and `apibank` is one subset of Web API rather than all of it. A model reproducing
# inside that tolerance validates the loader, the gold labels, the metric and the wiring.
MATCH_TOLERANCE = 5.0

# The ToolRet-tuned checkpoints have no published row, but each was fine-tuned *from* a
# model that does — so the base model's number is a floor the tuned one must clear by more
# than measurement noise. This is what keeps the check loud for our default model: the
# missing-instruction bug produced 25.52 against a base of 24.59, a +0.9 "gain" from
# fine-tuning on 200k in-domain examples, which is not a plausible result. Comparing to a
# 20-model spread would have shrugged at it; comparing to its own base does not.
TUNED_BASE = {
    "mangopy/ToolRet-trained-e5-base-v2": "intfloat/e5-base-v2",
    "mangopy/ToolRet-trained-e5-large-v2": "intfloat/e5-large-v2",
    "mangopy/ToolRet-trained-bge-large-en-v1.5": "BAAI/bge-large-en-v1.5",
}


def published_table(use_instruction: bool) -> dict[str, tuple[float, float]]:
    return PUBLISHED_API_WITH_INST if use_instruction else PUBLISHED_API_NO_INST


def verdict(ndcg_pct: float, model_id: str, use_instruction: bool) -> str:
    """Is our number plausibly the same measurement as the published one?"""
    table = published_table(use_instruction)
    setting = "w/ meta w/ inst" if use_instruction else "w/ meta w/o inst"
    scores = sorted((v[0] for v in table.values()), reverse=True)
    low, high = scores[-1], scores[0]

    if model_id in table:
        published = table[model_id][0]
        delta = ndcg_pct - published
        if abs(delta) <= MATCH_TOLERANCE:
            return (
                f"REPRODUCES {model_id} on the '{setting}' / Web API tab: published "
                f"{published:.2f}, ours {ndcg_pct:.2f} ({delta:+.2f}). Within the ±"
                f"{MATCH_TOLERANCE:.0f} tolerance — loader, gold labels, metric and wiring "
                "all check out."
            )
        return (
            f"DOES NOT REPRODUCE {model_id} on the '{setting}' / Web API tab: published "
            f"{published:.2f}, ours {ndcg_pct:.2f} ({delta:+.2f}), outside the ±"
            f"{MATCH_TOLERANCE:.0f} tolerance. This is a like-for-like comparison — same "
            "model, same setting, same category — so corpus size and subset choice are the "
            "only benign explanations, and neither should move it this far. Check the "
            "document text we index against what the leaderboard indexes ('w/ meta' means "
            "the full tool documentation), and the tokenizer."
        )

    rank = sum(1 for s in scores if s > ndcg_pct) + 1
    position = (
        f"On the '{setting}' / Web API tab it ranks {rank} of {len(scores) + 1}, against a "
        f"published spread of {low:.2f}–{high:.2f}."
    )

    base = TUNED_BASE.get(model_id)
    if base and base in table:
        base_score = table[base][0]
        gain = ndcg_pct - base_score
        if gain <= MATCH_TOLERANCE:
            return (
                f"SUSPECT: {model_id} scored {ndcg_pct:.2f} against its own base {base} at "
                f"{base_score:.2f} — a gain of only {gain:+.2f} from fine-tuning on 200k "
                f"in-domain examples, which is not a plausible result. {position} Check the "
                "setting first: is the instruction being applied when it should be?"
            )
        return (
            f"{model_id} beats its base {base} by {gain:+.2f} ({base_score:.2f} → "
            f"{ndcg_pct:.2f}) on the '{setting}' / Web API tab — the expected shape for a "
            f"tuned checkpoint. {position} Note it means the retriever saw this benchmark's "
            "training split, which flatters baseline 4 — the conservative direction for "
            "Gate 0."
        )

    return (
        f"no published row for {model_id} and no known base model to compare against. "
        f"{position}"
    )


def build_scorer(name: str, catalog: Catalog) -> RelevanceScorer:
    if name == "bm25":
        return BM25Scorer(catalog)
    from .embedding import EmbeddingScorer

    return EmbeddingScorer(catalog, model_name=CALIBRATION_MODELS[name])


def rank_of_required(
    scorer: RelevanceScorer,
    example: Example,
    catalog: Catalog,
    depth: int,
    use_instruction: bool = True,
) -> list[int]:
    """1-based ranks of each required tool in the retrieved list. ``depth+1`` if unranked."""
    # retrieval_text, not task: the published leaderboard's "w/ inst" setting prepends
    # ToolRet's per-query instruction. Comparing our query-only score against their
    # w/-inst numbers is what put us below BM25.
    query = example.retrieval_text if use_instruction else example.task
    scored = sorted(catalog, key=lambda t: (-scorer.score(query, t), t.name))
    positions = {t.key: i + 1 for i, t in enumerate(scored[:depth])}
    return [positions.get(key, depth + 1) for key in example.required]


def ndcg_at_k(ranks: list[int], n_relevant: int, k: int) -> float:
    dcg = sum(1.0 / math.log2(r + 1) for r in ranks if r <= k)
    ideal = sum(1.0 / math.log2(i + 2) for i in range(min(n_relevant, k)))
    return dcg / ideal if ideal else 0.0


def evaluate_retriever(
    scorer: RelevanceScorer,
    examples: list[Example],
    catalog: Catalog,
    k: int = 10,
    use_instruction: bool = True,
) -> dict:
    depth = max(k, 100)
    ndcg_sum = recall_sum = hit1 = 0.0

    for example in examples:
        ranks = rank_of_required(scorer, example, catalog, depth, use_instruction)
        ndcg_sum += ndcg_at_k(ranks, len(example.required), k)
        recall_sum += sum(1 for r in ranks if r <= k) / len(ranks)
        if min(ranks) == 1:
            hit1 += 1

    n = max(len(examples), 1)
    return {
        f"ndcg@{k}": round(ndcg_sum / n, 4),
        f"recall@{k}": round(recall_sum / n, 4),
        "hit@1": round(hit1 / n, 4),
        "n_examples": len(examples),
        "catalog_size": len(catalog),
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Calibrate against a published retriever.")
    parser.add_argument("--model", default="toolret-e5-base", choices=SCORERS)
    parser.add_argument("--tools-subset", default="web")
    parser.add_argument("--queries-subset", default="apibank")
    parser.add_argument("--tool-limit", type=int, default=None)
    parser.add_argument("--query-limit", type=int, default=200)
    parser.add_argument("-k", type=int, default=10)
    parser.add_argument(
        "--no-instruction",
        action="store_true",
        help="score query-only, matching the leaderboard's w/o-inst tab",
    )
    parser.add_argument("--out", type=Path, default=Path("results/calibration.json"))
    args = parser.parse_args(argv)

    catalog = load_catalog(args.tools_subset, limit=args.tool_limit)
    examples = restrict_to_catalog(
        load_examples(args.queries_subset, limit=args.query_limit), catalog
    )
    scorer = build_scorer(args.model, catalog)
    metrics = evaluate_retriever(
        scorer, examples, catalog, k=args.k, use_instruction=not args.no_instruction
    )
    metrics["setting"] = "w/o inst" if args.no_instruction else "w/ inst"
    metrics["model"] = CALIBRATION_MODELS.get(args.model, args.model)

    import json

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(metrics, indent=2))
    for key, value in metrics.items():
        print(f"{key:>14}: {value}")
    ndcg_pct = metrics[f"ndcg@{args.k}"] * 100
    print(
        f"\nnDCG@{args.k} = {ndcg_pct:.2f}% — "
        f"{verdict(ndcg_pct, metrics['model'], not args.no_instruction)}"
    )
    print(
        "Reference is the ToolRet leaderboard, category Web API, setting matched to "
        "--no-instruction. `apibank` is a Web API subset, so the 'All' tab is never the "
        "right comparison."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
