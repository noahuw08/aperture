# BM25 needs no download and no GPU, and it is the published band's floor — so it is both
# the cheapest calibration point and the most diagnostic. Ordering is what we actually
# check: sparse < general dense < tool-tuned dense. Absolute nDCG is protocol-sensitive;
# the ordering is robust to protocol, which is why one number was never enough.
SCORERS = ["bm25", *CALIBRATION_MODELS]


